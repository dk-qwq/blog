export interface MarkdownDocument {
	html: string;
	title: string;
	description?: string;
	hasBodyTitle: boolean;
	warnings: string[];
	/** Trusted styles generated by Expressive Code, never styles from the input. */
	styles: string[];
}

const admonitionTypes = [
	"note",
	"tip",
	"important",
	"caution",
	"warning",
] as const;

// Sanitize user HTML before adding trusted component, KaTeX and code markup.
// This keeps generated SVG/MathML/inline colors without accepting those from MD.
const htmlIdPrefix = "user-content-";
const inputSchema = {
	...defaultSchema,
	clobberPrefix: htmlIdPrefix,
	tagNames: [
		...(defaultSchema.tagNames ?? []),
		...admonitionTypes,
		"github",
		"spoiler",
	],
	attributes: {
		...defaultSchema.attributes,
		"*": [...(defaultSchema.attributes?.["*"] ?? []), "className"],
		code: ["className", "dataMarkdownMeta"],
		github: ["repo"],
		...Object.fromEntries(
			admonitionTypes.map((type) => [type, ["has-directive-label"]]),
		),
	},
	strip: [
		...(defaultSchema.strip ?? []),
		"style",
		"iframe",
		"object",
		"embed",
		"template",
	],
};

/** Keep fragment links and accessible labels aligned with sanitized IDs. */
function preserveLocalReferences() {
	return (tree: HastRoot) => {
		const targets = new Map<string, string>();
		visit(tree, "element", (node) => {
			const id = node.properties.id;
			if (typeof id === "string" && id.startsWith(htmlIdPrefix)) {
				targets.set(id.slice(htmlIdPrefix.length), id);
			}
		});
		visit(tree, "element", (node) => {
			const href = node.properties.href;
			if (typeof href === "string" && href.startsWith("#")) {
				let target = href.slice(1);
				try {
					target = decodeURIComponent(target);
				} catch {
					// Keep malformed URL escapes as literal anchor names.
				}
				const id = targets.get(target);
				if (id) node.properties.href = `#${id}`;
			}
			for (const property of ["ariaDescribedBy", "ariaLabelledBy", "headers"]) {
				const value = node.properties[property];
				if (Array.isArray(value)) {
					node.properties[property] = value.map((id) =>
						typeof id === "string" ? (targets.get(id) ?? id) : id,
					);
				} else if (typeof value === "string") {
					node.properties[property] = value
						.split(/\s+/)
						.map((id) => targets.get(id) ?? id)
						.join(" ");
				}
			}
		});
	};
}

let codeEngine: Promise<ExpressiveCode> | undefined;

function getCodeEngine(): Promise<ExpressiveCode> {
	codeEngine ??= loadShikiTheme("dark-plus").then(
		(theme) =>
			new ExpressiveCode({
				themes: [theme],
				// Astro's EC integration removes the other engine from client bundles.
				// Match the blog's default so preview highlighting survives production.
				shiki: { engine: "oniguruma" },
				plugins: [
					pluginCollapsibleSections(),
					pluginLineNumbers(),
					pluginLanguageBadge(),
				],
				defaultProps: {
					wrap: true,
					showLineNumbers: false,
					frame: "none",
					collapseStyle: "collapsible-start",
				},
				frames: { showCopyToClipboardButton: false },
				styleOverrides: {
					codeBackground: "#1E1E1E",
					borderRadius: "0.5rem",
					borderColor: "none",
					codeFontSize: "0.875rem",
					codeFontFamily:
						"'JetBrains Mono Variable', Menlo, Monaco, Consolas, 'Courier New', ui-monospace, monospace",
					codeLineHeight: "1.5rem",
					frames: {
						editorBackground: "#1E1E1E",
						terminalBackground: "#1E1E1E",
						terminalTitlebarBackground: "#2D2D2D",
						editorTabBarBackground: "#2D2D2D",
						editorActiveTabBackground: "#1E1E1E",
						editorActiveTabIndicatorBottomColor: "#007ACC",
						editorActiveTabIndicatorTopColor: "none",
						editorTabBarBorderBottomColor: "#2D2D2D",
						terminalTitlebarBorderBottomColor: "none",
					},
					textMarkers: { delHue: "0", insHue: "120", markHue: "60" },
					collapsibleSections: {
						openBackgroundColorCollapsible: "rgb(0, 0, 0 / 0)",
					},
				},
			}),
	);
	return codeEngine;
}

function frontmatter(source: string, warnings: string[]) {
	const normalized = source.replace(/^\uFEFF/, "");
	const match =
		/^---[\t ]*\r?\n([\s\S]*?)\r?\n(?:---|\.\.\.)[\t ]*(?:\r?\n|$)/.exec(
			normalized,
		);
	if (!match)
		return { body: normalized, title: undefined, description: undefined };
	const body = normalized.slice(match[0].length);
	try {
		const document = parseDocument(match[1], {
			schema: "core",
			uniqueKeys: true,
		});
		if (document.errors.length) throw document.errors[0];
		const metadata: unknown = document.toJS({ maxAliasCount: 100 });
		const fields =
			metadata && typeof metadata === "object"
				? (metadata as Record<string, unknown>)
				: {};
		return {
			body,
			title:
				typeof fields.title === "string"
					? fields.title.trim() || undefined
					: undefined,
			description:
				typeof fields.description === "string"
					? fields.description.trim() || undefined
					: undefined,
		};
	} catch {
		warnings.push("文件开头的 YAML 信息无法解析，已使用正文或文件名作为标题。");
		return { body, title: undefined, description: undefined };
	}
}

function githubCard(properties: Element["properties"]): Element {
	const repo = String(properties.repo ?? "");
	if (!/^[\w.-]+\/[\w.-]+$/.test(repo)) {
		return h("p", "GitHub 仓库格式无效，请使用 owner/repo。");
	}
	const [owner, name] = repo.split("/");
	return h(
		"a",
		{
			className: ["card-github", "no-styling"],
			href: `https://github.com/${repo}`,
			dataGithubRepo: repo,
		},
		[
			h("div.gc-titlebar", [
				h("div.gc-titlebar-left", [
					h("div.gc-owner", [h("div.gc-user", owner)]),
					h("div.gc-divider", "/"),
					h("div.gc-repo", name),
				]),
				h("div.github-logo"),
			]),
			h("div.gc-description", `github.com/${repo}`),
		],
	);
}

function elementText(node: RootContent): string {
	if (node.type === "text") return node.value;
	return "children" in node ? node.children.map(elementText).join("") : "";
}

function renderCodeBlocks(styles: Set<string>, warnings: string[]) {
	return async (tree: HastRoot) => {
		const blocks: {
			node: Element;
			parent: HastRoot | Element;
			index: number;
		}[] = [];
		visit(tree, "element", (node, index, parent) => {
			if (
				node.tagName === "pre" &&
				index !== undefined &&
				parent &&
				node.children.length === 1 &&
				node.children[0].type === "element" &&
				node.children[0].tagName === "code"
			)
				blocks.push({ node: node.children[0], parent, index });
		});
		if (!blocks.length) return;
		const engine = await getCodeEngine();
		for (const block of blocks) {
			const classes = block.node.properties.className;
			const language =
				(Array.isArray(classes) ? classes : [])
					.map(String)
					.find((name) => name.startsWith("language-"))
					?.slice(9) || "text";
			// Display math also uses pre > code until KaTeX runs.
			if (language === "math") continue;
			try {
				const rendered = await engine.render({
					code: elementText(block.node).replace(/\n$/, ""),
					language,
					meta:
						typeof block.node.properties.dataMarkdownMeta === "string"
							? block.node.properties.dataMarkdownMeta
							: "",
				});
				block.parent.children[block.index] = rendered.renderedGroupAst;
				for (const style of rendered.styles) styles.add(style);
			} catch {
				warnings.push(
					`有一个 ${language} 代码块无法应用高亮或扩展标记，已保留完整代码。`,
				);
			}
		}
		styles.add(await engine.getBaseStyles());
		styles.add(await engine.getThemeStyles());
	};
}

/** Render locally with the same Markdown extensions and code presentation as posts. */
export async function renderMarkdownDocument(
	source: string,
	fallbackTitle = "未命名文档",
): Promise<MarkdownDocument> {
	const warnings: string[] = [];
	const styles = new Set<string>();
	const metadata = frontmatter(source, warnings);
	let firstHeading: string | undefined;
	const processor = unified()
		.use(remarkParse)
		.use(remarkGfm)
		.use(remarkMath)
		.use(remarkGithubAdmonitionsToDirectives)
		.use(remarkDirective)
		.use(() => (tree: MdastRoot) => {
			visit(tree, "heading", (heading: Heading) => {
				if (heading.depth === 1 && firstHeading === undefined)
					firstHeading = mdastText(heading).trim();
			});
		})
		.use(remarkSectionize)
		.use(() => (tree: MdastRoot) => parseDirectiveNode()(tree, { _data: {} }))
		.use(remarkRehype, { allowDangerousHtml: true, footnoteLabel: "脚注" })
		.use(() => (tree: HastRoot) => {
			visit(tree, "element", (node) => {
				if (node.tagName === "code" && typeof node.data?.meta === "string") {
					node.properties.dataMarkdownMeta = node.data.meta;
				}
				if (node.properties["has-directive-label"]) {
					node.properties["has-directive-label"] = "true";
				}
			});
		})
		.use(rehypeRaw)
		.use(rehypeSanitize, inputSchema)
		.use(preserveLocalReferences)
		.use(rehypeKatex, { trust: false, strict: "warn" })
		.use(rehypeSlug)
		.use(rehypeComponents, {
			components: {
				github: githubCard,
				...Object.fromEntries(
					admonitionTypes.map((type) => [
						type,
						(
							properties: Element["properties"],
							children: Element["children"],
						) => AdmonitionComponent(properties, children, type),
					]),
				),
			},
		})
		.use(() => renderCodeBlocks(styles, warnings))
		.use(rehypeAutolinkHeadings, {
			behavior: "append",
			properties: { className: ["anchor"] },
			content: h("span.anchor-icon", { dataPagefindIgnore: true }, "#"),
		})
		.use(rehypeStringify);
	const result = await processor.process(metadata.body);
	if (result.messages.some((message) => message.source === "rehype-katex")) {
		warnings.push(
			"部分公式无法完整解析，已在预览中保留错误提示，请检查公式语法。",
		);
	}
	const title =
		metadata.title || firstHeading || fallbackTitle.trim() || "未命名文档";
	return {
		html: String(result),
		title,
		description: metadata.description,
		hasBodyTitle: firstHeading === title,
		warnings: [...new Set(warnings)],
		styles: [...styles],
	};
}
